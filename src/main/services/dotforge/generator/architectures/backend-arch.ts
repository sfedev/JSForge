/**
 * Variantes arquitectonicas de servidor.
 *
 * Las dos generan la misma funcionalidad —un CRUD minimo de items— para que
 * la diferencia entre ellas sea exactamente la organizacion del codigo y la
 * direccion de las dependencias, y no el alcance del ejemplo.
 */

import type { ArchitectureTree } from './types.js';

export type BackendArchitecture = 'hexagonal' | 'layered';
export type BackendFramework = 'express' | 'nestjs' | 'fastify';

/* -------------------------------------------------------------------------- */
/*  Hexagonal: puertos y adaptadores                                           */
/* -------------------------------------------------------------------------- */

function hexagonal(framework: BackendFramework): ArchitectureTree {
  const files = new Map<string, string>();

  /* --- Dominio: no importa nada --- */
  files.set(
    'src/domain/item.ts',
    [
      '/**',
      ' * Entidad del dominio. No conoce el framework, ni la base de datos, ni',
      ' * el transporte: solo las reglas del negocio.',
      ' */',
      'export interface Item {',
      '  readonly id: string;',
      '  readonly nombre: string;',
      '  readonly cantidad: number;',
      '  readonly creadoEn: Date;',
      '}',
      '',
      'export class ItemInvalidoError extends Error {',
      '  public constructor(motivo: string) {',
      '    super(`Item invalido: ${motivo}`);',
      "    this.name = 'ItemInvalidoError';",
      '  }',
      '}',
      '',
      '/** Invariante del dominio, comprobada al crear. */',
      'export function crearItem(nombre: string, cantidad: number, id: string): Item {',
      "  if (nombre.trim() === '') {",
      "    throw new ItemInvalidoError('el nombre no puede estar vacio');",
      '  }',
      '  if (!Number.isInteger(cantidad) || cantidad <= 0) {',
      "    throw new ItemInvalidoError('la cantidad debe ser un entero positivo');",
      '  }',
      '  return { id, nombre: nombre.trim(), cantidad, creadoEn: new Date() };',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/domain/ports/item-repository.ts',
    [
      "import type { Item } from '../item.js';",
      '',
      '/**',
      ' * Puerto de salida. El dominio declara lo que necesita; los adaptadores',
      ' * deciden como cumplirlo.',
      ' */',
      'export interface ItemRepository {',
      '  listar(): Promise<readonly Item[]>;',
      '  buscarPorId(id: string): Promise<Item | null>;',
      '  guardar(item: Item): Promise<void>;',
      '  eliminar(id: string): Promise<boolean>;',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/domain/ports/id-generator.ts',
    [
      '/** Puerto de identificadores: permite fijarlos en las pruebas. */',
      'export interface IdGenerator {',
      '  siguiente(): string;',
      '}',
      '',
    ].join('\n'),
  );

  /* --- Aplicacion: casos de uso --- */
  files.set(
    'src/application/crear-item.ts',
    [
      "import { crearItem, type Item } from '../domain/item.js';",
      "import type { IdGenerator } from '../domain/ports/id-generator.js';",
      "import type { ItemRepository } from '../domain/ports/item-repository.js';",
      '',
      'export interface CrearItemEntrada {',
      '  readonly nombre: string;',
      '  readonly cantidad: number;',
      '}',
      '',
      '/**',
      ' * Caso de uso. Recibe sus dependencias por parametro, asi que se prueba',
      ' * sin base de datos y sin levantar el servidor.',
      ' */',
      'export function crearItemUseCase(repositorio: ItemRepository, generador: IdGenerator) {',
      '  return async function ejecutar(entrada: CrearItemEntrada): Promise<Item> {',
      '    const item = crearItem(entrada.nombre, entrada.cantidad, generador.siguiente());',
      '    await repositorio.guardar(item);',
      '    return item;',
      '  };',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/application/listar-items.ts',
    [
      "import type { Item } from '../domain/item.js';",
      "import type { ItemRepository } from '../domain/ports/item-repository.js';",
      '',
      'export function listarItemsUseCase(repositorio: ItemRepository) {',
      '  return async function ejecutar(): Promise<readonly Item[]> {',
      '    return repositorio.listar();',
      '  };',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/application/crear-item.test.ts',
    [
      "import { describe, expect, it } from 'vitest';",
      '',
      "import { crearItemUseCase } from './crear-item.js';",
      "import type { Item } from '../domain/item.js';",
      "import type { ItemRepository } from '../domain/ports/item-repository.js';",
      '',
      '/** Doble en memoria: el caso de uso no necesita infraestructura real. */',
      'function repositorioFalso(): ItemRepository & { almacen: Item[] } {',
      '  const almacen: Item[] = [];',
      '  return {',
      '    almacen,',
      '    listar: async () => almacen,',
      '    buscarPorId: async (id) => almacen.find((item) => item.id === id) ?? null,',
      '    guardar: async (item) => {',
      '      almacen.push(item);',
      '    },',
      '    eliminar: async (id) => {',
      '      const indice = almacen.findIndex((item) => item.id === id);',
      '      if (indice === -1) {',
      '        return false;',
      '      }',
      '      almacen.splice(indice, 1);',
      '      return true;',
      '    },',
      '  };',
      '}',
      '',
      "describe('crearItemUseCase', () => {",
      "  it('guarda el item y devuelve la entidad creada', async () => {",
      '    const repositorio = repositorioFalso();',
      "    const ejecutar = crearItemUseCase(repositorio, { siguiente: () => 'id-1' });",
      '',
      "    const item = await ejecutar({ nombre: 'Tornillo', cantidad: 3 });",
      '',
      "    expect(item.id).toBe('id-1');",
      '    expect(repositorio.almacen).toHaveLength(1);',
      '  });',
      '',
      "  it('rechaza una cantidad no positiva y no guarda nada', async () => {",
      '    const repositorio = repositorioFalso();',
      "    const ejecutar = crearItemUseCase(repositorio, { siguiente: () => 'id-1' });",
      '',
      "    await expect(ejecutar({ nombre: 'Tornillo', cantidad: 0 })).rejects.toThrow();",
      '    expect(repositorio.almacen).toHaveLength(0);',
      '  });',
      '});',
      '',
    ].join('\n'),
  );

  /* --- Infraestructura: adaptadores de salida --- */
  files.set(
    'src/infrastructure/persistence/memory-item-repository.ts',
    [
      "import type { Item } from '../../domain/item.js';",
      "import type { ItemRepository } from '../../domain/ports/item-repository.js';",
      '',
      '/** Adaptador en memoria: sirve para arrancar y para las pruebas. */',
      'export class MemoryItemRepository implements ItemRepository {',
      '  readonly #items = new Map<string, Item>();',
      '',
      '  public async listar(): Promise<readonly Item[]> {',
      '    return [...this.#items.values()];',
      '  }',
      '',
      '  public async buscarPorId(id: string): Promise<Item | null> {',
      '    return this.#items.get(id) ?? null;',
      '  }',
      '',
      '  public async guardar(item: Item): Promise<void> {',
      '    this.#items.set(item.id, item);',
      '  }',
      '',
      '  public async eliminar(id: string): Promise<boolean> {',
      '    return this.#items.delete(id);',
      '  }',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/infrastructure/uuid-generator.ts',
    [
      "import type { IdGenerator } from '../domain/ports/id-generator.js';",
      '',
      'export class UuidGenerator implements IdGenerator {',
      '  public siguiente(): string {',
      '    return crypto.randomUUID();',
      '  }',
      '}',
      '',
    ].join('\n'),
  );

  /* --- Adaptadores de entrada, segun el framework --- */
  if (framework === 'express') {
    files.set(
      'src/adapters/http/item-router.ts',
      [
        "import { Router } from 'express';",
        "import { z } from 'zod';",
        '',
        "import { crearItemUseCase } from '../../application/crear-item.js';",
        "import { listarItemsUseCase } from '../../application/listar-items.js';",
        "import { ItemInvalidoError } from '../../domain/item.js';",
        "import type { IdGenerator } from '../../domain/ports/id-generator.js';",
        "import type { ItemRepository } from '../../domain/ports/item-repository.js';",
        '',
        'const EsquemaCrear = z.object({',
        "  nombre: z.string().min(1, 'El nombre es obligatorio.'),",
        '  cantidad: z.number().int().positive().default(1),',
        '});',
        '',
        '/** Adaptador de entrada: traduce HTTP a casos de uso y vuelta. */',
        'export function crearItemRouter(repositorio: ItemRepository, generador: IdGenerator): Router {',
        '  const router = Router();',
        '  const listar = listarItemsUseCase(repositorio);',
        '  const crear = crearItemUseCase(repositorio, generador);',
        '',
        "  router.get('/', async (_peticion, respuesta) => {",
        '    respuesta.json({ items: await listar() });',
        '  });',
        '',
        "  router.post('/', async (peticion, respuesta) => {",
        '    const resultado = EsquemaCrear.safeParse(peticion.body);',
        '    if (!resultado.success) {',
        '      respuesta.status(422).json({ error: resultado.error.flatten() });',
        '      return;',
        '    }',
        '    try {',
        '      respuesta.status(201).json({ item: await crear(resultado.data) });',
        '    } catch (causa) {',
        '      if (causa instanceof ItemInvalidoError) {',
        '        respuesta.status(422).json({ error: causa.message });',
        '        return;',
        '      }',
        '      throw causa;',
        '    }',
        '  });',
        '',
        '  return router;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/adapters/http/server.ts',
      [
        "import cors from 'cors';",
        "import express, { type Express, type NextFunction, type Request, type Response } from 'express';",
        "import helmet from 'helmet';",
        "import pinoHttp from 'pino-http';",
        '',
        "import { MemoryItemRepository } from '../../infrastructure/persistence/memory-item-repository.js';",
        "import { UuidGenerator } from '../../infrastructure/uuid-generator.js';",
        "import { crearItemRouter } from './item-router.js';",
        '',
        'export function crearServidor(): Express {',
        '  const app = express();',
        '',
        '  app.use(helmet());',
        '  app.use(cors());',
        "  app.use(express.json({ limit: '1mb' }));",
        '  app.use(pinoHttp());',
        '',
        '  // Composicion: aqui se elige el adaptador concreto.',
        '  const repositorio = new MemoryItemRepository();',
        '  const generador = new UuidGenerator();',
        '',
        "  app.get('/health', (_peticion, respuesta) => {",
        "    respuesta.json({ estado: 'ok' });",
        '  });',
        '',
        "  app.use('/api/items', crearItemRouter(repositorio, generador));",
        '',
        '  // Manejador de errores: cuatro parametros, obligatorio en Express.',
        '  app.use((error: Error, _peticion: Request, respuesta: Response, _siguiente: NextFunction) => {',
        '    respuesta.status(500).json({ error: error.message });',
        '  });',
        '',
        '  return app;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/main.ts',
      [
        "import pino from 'pino';",
        '',
        "import { crearServidor } from './adapters/http/server.js';",
        '',
        'const log = pino();',
        "const puerto = Number.parseInt(process.env.PORT ?? '3000', 10);",
        '',
        'const servidor = crearServidor().listen(puerto, () => {',
        '  log.info(`Server listening on port ${puerto}`);',
        '});',
        '',
        '// Apagado ordenado: sin esto, un despliegue corta peticiones a medias.',
        "for (const senal of ['SIGINT', 'SIGTERM'] as const) {",
        '  process.on(senal, () => {',
        '    log.info(`Recibida ${senal}; cerrando el servidor.`);',
        '    servidor.close(() => process.exit(0));',
        '  });',
        '}',
        '',
      ].join('\n'),
    );
  } else if (framework === 'nestjs') {
    files.set(
      'src/adapters/http/items.controller.ts',
      [
        "import { Body, Controller, Get, Inject, Post } from '@nestjs/common';",
        '',
        "import { crearItemUseCase } from '../../application/crear-item.js';",
        "import { listarItemsUseCase } from '../../application/listar-items.js';",
        "import type { Item } from '../../domain/item.js';",
        "import type { IdGenerator } from '../../domain/ports/id-generator.js';",
        "import type { ItemRepository } from '../../domain/ports/item-repository.js';",
        "import { CrearItemDto } from './crear-item.dto.js';",
        "import { ID_GENERATOR, ITEM_REPOSITORY } from './tokens.js';",
        '',
        "@Controller('api/items')",
        'export class ItemsController {',
        '  constructor(',
        '    @Inject(ITEM_REPOSITORY) private readonly repositorio: ItemRepository,',
        '    @Inject(ID_GENERATOR) private readonly generador: IdGenerator,',
        '  ) {}',
        '',
        '  @Get()',
        '  async listar(): Promise<{ items: readonly Item[] }> {',
        '    return { items: await listarItemsUseCase(this.repositorio)() };',
        '  }',
        '',
        '  @Post()',
        '  async crear(@Body() datos: CrearItemDto): Promise<{ item: Item }> {',
        '    const ejecutar = crearItemUseCase(this.repositorio, this.generador);',
        '    return { item: await ejecutar(datos) };',
        '  }',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/adapters/http/crear-item.dto.ts',
      [
        "import { IsInt, IsPositive, IsString, MinLength } from 'class-validator';",
        '',
        'export class CrearItemDto {',
        '  @IsString()',
        "  @MinLength(1, { message: 'El nombre es obligatorio.' })",
        '  nombre!: string;',
        '',
        '  @IsInt()',
        '  @IsPositive()',
        '  cantidad!: number;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/adapters/http/tokens.ts',
      [
        '/**',
        ' * Tokens de inyeccion. Las interfaces de TypeScript no existen en',
        ' * tiempo de ejecucion, asi que Nest necesita un simbolo para resolver',
        ' * los puertos del dominio.',
        ' */',
        "export const ITEM_REPOSITORY = Symbol('ItemRepository');",
        "export const ID_GENERATOR = Symbol('IdGenerator');",
        '',
      ].join('\n'),
    );
    files.set(
      'src/adapters/http/items.module.ts',
      [
        "import { Module } from '@nestjs/common';",
        '',
        "import { MemoryItemRepository } from '../../infrastructure/persistence/memory-item-repository.js';",
        "import { UuidGenerator } from '../../infrastructure/uuid-generator.js';",
        "import { ItemsController } from './items.controller.js';",
        "import { ID_GENERATOR, ITEM_REPOSITORY } from './tokens.js';",
        '',
        '@Module({',
        '  controllers: [ItemsController],',
        '  providers: [',
        '    // El modulo es el unico que sabe que adaptador se usa.',
        '    { provide: ITEM_REPOSITORY, useClass: MemoryItemRepository },',
        '    { provide: ID_GENERATOR, useClass: UuidGenerator },',
        '  ],',
        '})',
        'export class ItemsModule {}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/app.module.ts',
      [
        "import { Controller, Get, Module } from '@nestjs/common';",
        "import { ConfigModule } from '@nestjs/config';",
        '',
        "import { ItemsModule } from './adapters/http/items.module.js';",
        '',
        "@Controller('health')",
        'class SaludController {',
        '  @Get()',
        '  comprobar(): { estado: string } {',
        "    return { estado: 'ok' };",
        '  }',
        '}',
        '',
        '@Module({',
        '  imports: [ConfigModule.forRoot({ isGlobal: true }), ItemsModule],',
        '  controllers: [SaludController],',
        '})',
        'export class AppModule {}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/main.ts',
      [
        "import 'reflect-metadata';",
        '',
        "import { ValidationPipe } from '@nestjs/common';",
        "import { NestFactory } from '@nestjs/core';",
        "import helmet from 'helmet';",
        '',
        "import { AppModule } from './app.module.js';",
        '',
        'async function arrancar(): Promise<void> {',
        '  const app = await NestFactory.create(AppModule);',
        '  app.use(helmet());',
        '  app.enableCors();',
        '  app.useGlobalPipes(',
        '    new ValidationPipe({ whitelist: true, forbidNonWhitelisted: true, transform: true }),',
        '  );',
        '  app.enableShutdownHooks();',
        "  await app.listen(Number.parseInt(process.env.PORT ?? '3000', 10));",
        '}',
        '',
        'void arrancar();',
        '',
      ].join('\n'),
    );
  } else {
    files.set(
      'src/adapters/http/items.plugin.ts',
      [
        "import type { FastifyPluginAsync } from 'fastify';",
        '',
        "import { crearItemUseCase } from '../../application/crear-item.js';",
        "import { listarItemsUseCase } from '../../application/listar-items.js';",
        "import { ItemInvalidoError } from '../../domain/item.js';",
        "import type { IdGenerator } from '../../domain/ports/id-generator.js';",
        "import type { ItemRepository } from '../../domain/ports/item-repository.js';",
        '',
        'interface Dependencias {',
        '  readonly repositorio: ItemRepository;',
        '  readonly generador: IdGenerator;',
        '}',
        '',
        'const esquemaCrear = {',
        '  body: {',
        "    type: 'object',",
        "    required: ['nombre'],",
        '    additionalProperties: false,',
        '    properties: {',
        "      nombre: { type: 'string', minLength: 1 },",
        "      cantidad: { type: 'integer', minimum: 1, default: 1 },",
        '    },',
        '  },',
        '} as const;',
        '',
        '/** Adaptador de entrada: Fastify valida antes de llegar al caso de uso. */',
        'export const itemsPlugin: FastifyPluginAsync<Dependencias> = async (app, opciones) => {',
        '  const listar = listarItemsUseCase(opciones.repositorio);',
        '  const crear = crearItemUseCase(opciones.repositorio, opciones.generador);',
        '',
        "  app.get('/', async () => ({ items: await listar() }));",
        '',
        "  app.post<{ Body: { nombre: string; cantidad?: number } }>(",
        "    '/',",
        '    { schema: esquemaCrear },',
        '    async (peticion, respuesta) => {',
        '      try {',
        '        const item = await crear({',
        '          nombre: peticion.body.nombre,',
        '          cantidad: peticion.body.cantidad ?? 1,',
        '        });',
        '        return respuesta.status(201).send({ item });',
        '      } catch (causa) {',
        '        if (causa instanceof ItemInvalidoError) {',
        '          return respuesta.unprocessableEntity(causa.message);',
        '        }',
        '        throw causa;',
        '      }',
        '    },',
        '  );',
        '};',
        '',
      ].join('\n'),
    );
    files.set(
      'src/adapters/http/app.ts',
      [
        "import cors from '@fastify/cors';",
        "import helmet from '@fastify/helmet';",
        "import sensible from '@fastify/sensible';",
        "import Fastify, { type FastifyInstance } from 'fastify';",
        '',
        "import { MemoryItemRepository } from '../../infrastructure/persistence/memory-item-repository.js';",
        "import { UuidGenerator } from '../../infrastructure/uuid-generator.js';",
        "import { itemsPlugin } from './items.plugin.js';",
        '',
        'export async function construirApp(): Promise<FastifyInstance> {',
        "  const app = Fastify({ logger: { level: process.env.LOG_LEVEL ?? 'info' } });",
        '',
        '  await app.register(helmet);',
        '  await app.register(cors);',
        '  await app.register(sensible);',
        '',
        '  // Composicion: aqui se eligen los adaptadores concretos.',
        '  await app.register(itemsPlugin, {',
        "    prefix: '/api/items',",
        '    repositorio: new MemoryItemRepository(),',
        '    generador: new UuidGenerator(),',
        '  });',
        '',
        "  app.get('/health', async () => ({ estado: 'ok' }));",
        '',
        '  return app;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/main.ts',
      [
        "import { construirApp } from './adapters/http/app.js';",
        '',
        "const puerto = Number.parseInt(process.env.PORT ?? '3000', 10);",
        'const app = await construirApp();',
        '',
        'try {',
        "  await app.listen({ port: puerto, host: '0.0.0.0' });",
        '} catch (causa) {',
        '  app.log.error(causa);',
        '  process.exit(1);',
        '}',
        '',
        "for (const senal of ['SIGINT', 'SIGTERM'] as const) {",
        '  process.on(senal, () => {',
        '    void app.close().then(() => process.exit(0));',
        '  });',
        '}',
        '',
      ].join('\n'),
    );
  }

  return {
    files,
    structure: [
      'src/',
      '  domain/           entidades, reglas y puertos (no importa nada)',
      '  application/      casos de uso, dependencias por parametro',
      '  infrastructure/   adaptadores de salida: persistencia, ids',
      '  adapters/http/    adaptador de entrada: rutas y validacion',
      '  main.ts           composicion y arranque',
    ],
    description:
      'Hexagonal (puertos y adaptadores): el dominio define interfaces y la infraestructura las implementa.',
    notes: [
      'La regla que sostiene todo: `domain/` no importa de ninguna otra carpeta.',
      'Cambiar de base de datos es escribir otro adaptador; ni el dominio ni los casos de uso se tocan.',
      'El repositorio en memoria permite arrancar y probar sin servidor de datos.',
    ],
  };
}

/* -------------------------------------------------------------------------- */
/*  Por capas                                                                  */
/* -------------------------------------------------------------------------- */

function layered(framework: BackendFramework): ArchitectureTree {
  const files = new Map<string, string>();

  files.set(
    'src/entities/item.entity.ts',
    [
      '/** Entidad: la forma de los datos que atraviesa las capas. */',
      'export interface Item {',
      '  readonly id: string;',
      '  readonly nombre: string;',
      '  readonly cantidad: number;',
      '  readonly creadoEn: Date;',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/repositories/item.repository.ts',
    [
      "import type { Item } from '../entities/item.entity.js';",
      '',
      '/**',
      ' * Repositorio: la unica capa que habla con el almacenamiento.',
      ' * Sustituirlo por uno con base de datos no obliga a tocar el servicio.',
      ' */',
      'export class ItemRepository {',
      '  readonly #items = new Map<string, Item>();',
      '',
      '  async findAll(): Promise<readonly Item[]> {',
      '    return [...this.#items.values()];',
      '  }',
      '',
      '  async findById(id: string): Promise<Item | null> {',
      '    return this.#items.get(id) ?? null;',
      '  }',
      '',
      '  async save(item: Item): Promise<Item> {',
      '    this.#items.set(item.id, item);',
      '    return item;',
      '  }',
      '',
      '  async remove(id: string): Promise<boolean> {',
      '    return this.#items.delete(id);',
      '  }',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/services/item.service.ts',
    [
      "import type { Item } from '../entities/item.entity.js';",
      "import { ItemRepository } from '../repositories/item.repository.js';",
      '',
      'export class ItemNoEncontradoError extends Error {',
      '  public constructor(id: string) {',
      '    super(`No existe el item ${id}.`);',
      "    this.name = 'ItemNoEncontradoError';",
      '  }',
      '}',
      '',
      'export class DatosInvalidosError extends Error {',
      '  public constructor(motivo: string) {',
      '    super(motivo);',
      "    this.name = 'DatosInvalidosError';",
      '  }',
      '}',
      '',
      '/**',
      ' * Servicio: contiene las reglas de negocio. No sabe nada de HTTP ni de',
      ' * como se guardan los datos.',
      ' */',
      'export class ItemService {',
      '  readonly #repositorio: ItemRepository;',
      '',
      '  public constructor(repositorio = new ItemRepository()) {',
      '    this.#repositorio = repositorio;',
      '  }',
      '',
      '  async listar(): Promise<readonly Item[]> {',
      '    return this.#repositorio.findAll();',
      '  }',
      '',
      '  async buscar(id: string): Promise<Item> {',
      '    const item = await this.#repositorio.findById(id);',
      '    if (item === null) {',
      '      throw new ItemNoEncontradoError(id);',
      '    }',
      '    return item;',
      '  }',
      '',
      '  async crear(nombre: string, cantidad: number): Promise<Item> {',
      "    if (nombre.trim() === '') {",
      "      throw new DatosInvalidosError('El nombre es obligatorio.');",
      '    }',
      '    if (!Number.isInteger(cantidad) || cantidad <= 0) {',
      "      throw new DatosInvalidosError('La cantidad debe ser un entero positivo.');",
      '    }',
      '    return this.#repositorio.save({',
      '      id: crypto.randomUUID(),',
      '      nombre: nombre.trim(),',
      '      cantidad,',
      '      creadoEn: new Date(),',
      '    });',
      '  }',
      '}',
      '',
    ].join('\n'),
  );

  files.set(
    'src/services/item.service.test.ts',
    [
      "import { describe, expect, it } from 'vitest';",
      '',
      "import { DatosInvalidosError, ItemNoEncontradoError, ItemService } from './item.service.js';",
      '',
      "describe('ItemService', () => {",
      "  it('crea y recupera un item', async () => {",
      '    const servicio = new ItemService();',
      "    const item = await servicio.crear('Tuerca', 2);",
      '',
      '    expect(await servicio.buscar(item.id)).toEqual(item);',
      '    expect(await servicio.listar()).toHaveLength(1);',
      '  });',
      '',
      "  it('rechaza datos invalidos', async () => {",
      '    const servicio = new ItemService();',
      "    await expect(servicio.crear('', 1)).rejects.toThrow(DatosInvalidosError);",
      "    await expect(servicio.crear('Tuerca', 0)).rejects.toThrow(DatosInvalidosError);",
      '  });',
      '',
      "  it('avisa si el item no existe', async () => {",
      '    const servicio = new ItemService();',
      "    await expect(servicio.buscar('desconocido')).rejects.toThrow(ItemNoEncontradoError);",
      '  });',
      '});',
      '',
    ].join('\n'),
  );

  if (framework === 'express') {
    files.set(
      'src/controllers/item.controller.ts',
      [
        "import { Router } from 'express';",
        '',
        "import { DatosInvalidosError, ItemNoEncontradoError, ItemService } from '../services/item.service.js';",
        '',
        '/**',
        ' * Controlador: traduce HTTP a llamadas al servicio. No contiene reglas',
        ' * de negocio, solo codigos de estado y forma de la respuesta.',
        ' */',
        'export function crearItemController(servicio = new ItemService()): Router {',
        '  const router = Router();',
        '',
        "  router.get('/', async (_peticion, respuesta) => {",
        '    respuesta.json({ items: await servicio.listar() });',
        '  });',
        '',
        "  router.get('/:id', async (peticion, respuesta) => {",
        '    try {',
        '      respuesta.json({ item: await servicio.buscar(peticion.params.id) });',
        '    } catch (causa) {',
        '      if (causa instanceof ItemNoEncontradoError) {',
        '        respuesta.status(404).json({ error: causa.message });',
        '        return;',
        '      }',
        '      throw causa;',
        '    }',
        '  });',
        '',
        "  router.post('/', async (peticion, respuesta) => {",
        '    const { nombre, cantidad } = peticion.body as { nombre?: string; cantidad?: number };',
        '    try {',
        "      const item = await servicio.crear(nombre ?? '', cantidad ?? 1);",
        '      respuesta.status(201).json({ item });',
        '    } catch (causa) {',
        '      if (causa instanceof DatosInvalidosError) {',
        '        respuesta.status(422).json({ error: causa.message });',
        '        return;',
        '      }',
        '      throw causa;',
        '    }',
        '  });',
        '',
        '  return router;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/app.ts',
      [
        "import cors from 'cors';",
        "import express, { type Express, type NextFunction, type Request, type Response } from 'express';",
        "import helmet from 'helmet';",
        "import pinoHttp from 'pino-http';",
        '',
        "import { crearItemController } from './controllers/item.controller.js';",
        '',
        'export function crearServidor(): Express {',
        '  const app = express();',
        '',
        '  app.use(helmet());',
        '  app.use(cors());',
        "  app.use(express.json({ limit: '1mb' }));",
        '  app.use(pinoHttp());',
        '',
        "  app.get('/health', (_peticion, respuesta) => {",
        "    respuesta.json({ estado: 'ok' });",
        '  });',
        '',
        "  app.use('/api/items', crearItemController());",
        '',
        '  app.use((error: Error, _peticion: Request, respuesta: Response, _siguiente: NextFunction) => {',
        '    respuesta.status(500).json({ error: error.message });',
        '  });',
        '',
        '  return app;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/main.ts',
      [
        "import pino from 'pino';",
        '',
        "import { crearServidor } from './app.js';",
        '',
        'const log = pino();',
        "const puerto = Number.parseInt(process.env.PORT ?? '3000', 10);",
        '',
        'const servidor = crearServidor().listen(puerto, () => {',
        '  log.info(`Server listening on port ${puerto}`);',
        '});',
        '',
        "for (const senal of ['SIGINT', 'SIGTERM'] as const) {",
        '  process.on(senal, () => {',
        '    log.info(`Recibida ${senal}; cerrando el servidor.`);',
        '    servidor.close(() => process.exit(0));',
        '  });',
        '}',
        '',
      ].join('\n'),
    );
  } else if (framework === 'nestjs') {
    files.set(
      'src/controllers/items.controller.ts',
      [
        "import { Body, Controller, Get, NotFoundException, Param, Post, UnprocessableEntityException } from '@nestjs/common';",
        '',
        "import type { Item } from '../entities/item.entity.js';",
        "import { CrearItemDto } from '../dto/crear-item.dto.js';",
        "import { DatosInvalidosError, ItemNoEncontradoError, ItemService } from '../services/item.service.js';",
        '',
        "@Controller('api/items')",
        'export class ItemsController {',
        '  constructor(private readonly servicio: ItemService) {}',
        '',
        '  @Get()',
        '  async listar(): Promise<{ items: readonly Item[] }> {',
        '    return { items: await this.servicio.listar() };',
        '  }',
        '',
        "  @Get(':id')",
        "  async buscar(@Param('id') id: string): Promise<{ item: Item }> {",
        '    try {',
        '      return { item: await this.servicio.buscar(id) };',
        '    } catch (causa) {',
        '      if (causa instanceof ItemNoEncontradoError) {',
        '        throw new NotFoundException(causa.message);',
        '      }',
        '      throw causa;',
        '    }',
        '  }',
        '',
        '  @Post()',
        '  async crear(@Body() datos: CrearItemDto): Promise<{ item: Item }> {',
        '    try {',
        '      return { item: await this.servicio.crear(datos.nombre, datos.cantidad) };',
        '    } catch (causa) {',
        '      if (causa instanceof DatosInvalidosError) {',
        '        throw new UnprocessableEntityException(causa.message);',
        '      }',
        '      throw causa;',
        '    }',
        '  }',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/dto/crear-item.dto.ts',
      [
        "import { IsInt, IsPositive, IsString, MinLength } from 'class-validator';",
        '',
        'export class CrearItemDto {',
        '  @IsString()',
        "  @MinLength(1, { message: 'El nombre es obligatorio.' })",
        '  nombre!: string;',
        '',
        '  @IsInt()',
        '  @IsPositive()',
        '  cantidad!: number;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/app.module.ts',
      [
        "import { Controller, Get, Module } from '@nestjs/common';",
        "import { ConfigModule } from '@nestjs/config';",
        '',
        "import { ItemsController } from './controllers/items.controller.js';",
        "import { ItemRepository } from './repositories/item.repository.js';",
        "import { ItemService } from './services/item.service.js';",
        '',
        "@Controller('health')",
        'class SaludController {',
        '  @Get()',
        '  comprobar(): { estado: string } {',
        "    return { estado: 'ok' };",
        '  }',
        '}',
        '',
        '@Module({',
        '  imports: [ConfigModule.forRoot({ isGlobal: true })],',
        '  controllers: [SaludController, ItemsController],',
        '  providers: [ItemRepository, ItemService],',
        '})',
        'export class AppModule {}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/main.ts',
      [
        "import 'reflect-metadata';",
        '',
        "import { ValidationPipe } from '@nestjs/common';",
        "import { NestFactory } from '@nestjs/core';",
        "import helmet from 'helmet';",
        '',
        "import { AppModule } from './app.module.js';",
        '',
        'async function arrancar(): Promise<void> {',
        '  const app = await NestFactory.create(AppModule);',
        '  app.use(helmet());',
        '  app.enableCors();',
        '  app.useGlobalPipes(',
        '    new ValidationPipe({ whitelist: true, forbidNonWhitelisted: true, transform: true }),',
        '  );',
        '  app.enableShutdownHooks();',
        "  await app.listen(Number.parseInt(process.env.PORT ?? '3000', 10));",
        '}',
        '',
        'void arrancar();',
        '',
      ].join('\n'),
    );
  } else {
    files.set(
      'src/controllers/items.controller.ts',
      [
        "import type { FastifyPluginAsync } from 'fastify';",
        '',
        "import { DatosInvalidosError, ItemNoEncontradoError, ItemService } from '../services/item.service.js';",
        '',
        'const esquemaCrear = {',
        '  body: {',
        "    type: 'object',",
        "    required: ['nombre'],",
        '    additionalProperties: false,',
        '    properties: {',
        "      nombre: { type: 'string', minLength: 1 },",
        "      cantidad: { type: 'integer', minimum: 1, default: 1 },",
        '    },',
        '  },',
        '} as const;',
        '',
        'export const itemsController: FastifyPluginAsync = async (app) => {',
        '  const servicio = new ItemService();',
        '',
        "  app.get('/', async () => ({ items: await servicio.listar() }));",
        '',
        "  app.get<{ Params: { id: string } }>('/:id', async (peticion, respuesta) => {",
        '    try {',
        '      return { item: await servicio.buscar(peticion.params.id) };',
        '    } catch (causa) {',
        '      if (causa instanceof ItemNoEncontradoError) {',
        '        return respuesta.notFound(causa.message);',
        '      }',
        '      throw causa;',
        '    }',
        '  });',
        '',
        "  app.post<{ Body: { nombre: string; cantidad?: number } }>(",
        "    '/',",
        '    { schema: esquemaCrear },',
        '    async (peticion, respuesta) => {',
        '      try {',
        '        const item = await servicio.crear(peticion.body.nombre, peticion.body.cantidad ?? 1);',
        '        return respuesta.status(201).send({ item });',
        '      } catch (causa) {',
        '        if (causa instanceof DatosInvalidosError) {',
        '          return respuesta.unprocessableEntity(causa.message);',
        '        }',
        '        throw causa;',
        '      }',
        '    },',
        '  );',
        '};',
        '',
      ].join('\n'),
    );
    files.set(
      'src/app.ts',
      [
        "import cors from '@fastify/cors';",
        "import helmet from '@fastify/helmet';",
        "import sensible from '@fastify/sensible';",
        "import Fastify, { type FastifyInstance } from 'fastify';",
        '',
        "import { itemsController } from './controllers/items.controller.js';",
        '',
        'export async function construirApp(): Promise<FastifyInstance> {',
        "  const app = Fastify({ logger: { level: process.env.LOG_LEVEL ?? 'info' } });",
        '',
        '  await app.register(helmet);',
        '  await app.register(cors);',
        '  await app.register(sensible);',
        "  await app.register(itemsController, { prefix: '/api/items' });",
        '',
        "  app.get('/health', async () => ({ estado: 'ok' }));",
        '',
        '  return app;',
        '}',
        '',
      ].join('\n'),
    );
    files.set(
      'src/main.ts',
      [
        "import { construirApp } from './app.js';",
        '',
        "const puerto = Number.parseInt(process.env.PORT ?? '3000', 10);",
        'const app = await construirApp();',
        '',
        'try {',
        "  await app.listen({ port: puerto, host: '0.0.0.0' });",
        '} catch (causa) {',
        '  app.log.error(causa);',
        '  process.exit(1);',
        '}',
        '',
        "for (const senal of ['SIGINT', 'SIGTERM'] as const) {",
        '  process.on(senal, () => {',
        '    void app.close().then(() => process.exit(0));',
        '  });',
        '}',
        '',
      ].join('\n'),
    );
  }

  return {
    files,
    structure: [
      'src/',
      '  controllers/   traduccion HTTP, sin reglas de negocio',
      '  services/      reglas de negocio',
      '  repositories/  acceso al almacenamiento',
      '  entities/      forma de los datos',
      '  main.ts        arranque',
    ],
    description:
      'Clean por capas: controlador, servicio y repositorio, cada capa hablando solo con la de abajo.',
    notes: [
      'El controlador no consulta el repositorio directamente: siempre pasa por el servicio.',
      'Los errores del dominio son clases propias; el controlador los traduce a codigos HTTP.',
    ],
  };
}

/* -------------------------------------------------------------------------- */

export function buildBackendArchitecture(
  architecture: BackendArchitecture,
  framework: BackendFramework,
): ArchitectureTree {
  return architecture === 'layered' ? layered(framework) : hexagonal(framework);
}
